# ruff: noqa: E501
from typing import Any

from app.ai_providers.base import BaseProvider, Message
from app.reviewer.compliance import _parse_json_safe

PROMPT = """你是一名"AI 味"检测员。你唯一的任务是判断这篇文章读起来像不像机器写的，并指出具体证据。

你不是编辑，不负责改进文章。严禁提出任何"建议补充/增加/完善"类的意见。

# 扣分项（发现一条记一条，在 issues 里写明具体位置并引用原文片段）

结构类：
- 用了"一、二、三"或"1. 2. 3."式编号小标题
- 开头先概述全文主题或交代"本文将讲什么"
- 结尾有总结段、升华句、"共勉""愿你""我们这代人"之类的收束
- 段落长度高度均匀（大部分段落字数接近）

句式类：
- 排比三连（三个结构相同的并列句或并列小节）
- 工整对仗的短语或小标题（如"三张牌桌，三套规则"）
- "不仅是…更是…"、"与其说…不如说…"
- 成语连用、四字词堆砌
- 每段末尾都有一句总结句、点题句或金句

内容类：
- 空泛过渡句："数据不会骗人""不难发现""值得注意的是""在这个时代""随着…的发展"
- 建议或要点恰好凑成 3 条或 5 条且格式完全对称
- 存在可以原样搬到任何话题上的段落（正确的废话）
- 通篇没有具体的人名、数字、时间、场景细节

# 加分项（这些是"人味"的证据，绝不要当成缺点报出来）
- 段落长短悬殊，有一句话成段
- 有跑题的闲笔、没说完的话、"我也没想明白"这类
- 口语词尾（吧、呢、了）、不完整句
- 具体到能看见画面的场景细节
- 结尾落在一个具体动作或开放问题上，而不是总结

# 评分
score 为 0-100 的整数，表示"人味程度"：100 = 完全看不出 AI 痕迹，0 = 通篇模板。
每命中一条扣分项，酌情扣 5-15 分。没有扣分项时 issues 为空数组，score 给 90 以上。

# 举证规则（严格执行）
issues 每一条都必须包含一段**从正文里逐字复制**的引文。
先写命中的扣分项名称，再接 " | 原文引证：" 和逐字片段。像这样：

  排比三连 | 原文引证：缴费责任倒挂、退休待遇倒挂、制度红利倒挂
  结尾升华句 | 原文引证：规则可以不对等，但别让自己的人生也押错注。

注意上面两行里的"排比三连""结尾升华句"是示例扣分项，你要换成实际命中的那一项，
不要原样输出示例文字，也不要输出"扣分项名称"这几个字。
引证必须能在正文中一字不差地检索到。你在写引证前，先回到正文确认这段字确实存在。
如果你觉得某处有问题但找不到可逐字引用的片段，就不要报这一条——
宁可漏报，也不许凭印象编造引证。已知的常见错误是：把"随着…的发展"这类
套话当成已出现，但正文里其实并没有。不要犯这个错。

# 严禁输出的意见类型（这些会把文章推回 AI 腔，一律不许写）
- "建议在开头介绍文章主题和目的"
- "建议补充权威依据/医学依据/研究数据/专家观点"
- "建议增加小标题使结构更清晰"
- "建议在结尾总结全文"
- 任何要求文章更完整、更全面、更有说服力的意见

输出严格 JSON：{"score": 0-100, "issues": [...]}。"""


async def review_quality(
    *,
    provider: BaseProvider,
    model: str,
    title: str,
    content: str,
) -> dict[str, Any]:
    user = f"【标题】{title}\n【正文】{content[:6000]}"
    result = await provider.chat(
        [
            Message(role="system", content=PROMPT),
            Message(role="user", content=user),
        ],
        model=model,
        json_mode=True,
        temperature=0.1,
    )
    parsed = _parse_json_safe(result.content)
    return {
        "score": int(parsed.get("score", 0)),
        "issues": list(parsed.get("issues") or []),
        "model": model,
    }
